"""Generate standalone, versioned Kaggle reviewer-response jobs from tested modules."""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def cell(kind, source):
    result = {"cell_type": kind, "metadata": {}, "source": source.splitlines(keepends=True)}
    if kind == "code":
        result.update(execution_count=None, outputs=[])
    return result


def build(output: Path | None = None, transfer_keys: tuple[str, ...] = ("table8|J->P",)) -> list[Path]:
    output = output or ROOT / "experiments/kaggle/revision"
    sources = {p.name: p.read_text(encoding="utf-8") for p in sorted((ROOT / "spectral_code/revision").glob("*.py"))}
    # Import only after fixing sys.path when this builder runs directly.
    from spectral_code.revision.training import ARMS
    written = []
    for arm in ARMS:
        group = "01_readout_controls" if arm in {"full", "mean_max", "attention", "projected", "projected_ast", "projected_ddg", "density_heat", "energy_only", "mean_max_classification_only", "attention_classification_only"} else "02_loss_controls"
        for seed in (42, 123, 231):
            path = output / group / f"codenet_{arm}_seed{seed}.ipynb"
            config = f'''# One arm and one seed per Kaggle Save & Run. Attach the audited bundle.
from pathlib import Path
import time
SESSION_STARTED = time.monotonic()  # includes imports and input preparation
ARM = {arm!r}
SEED = {seed}
MAX_EPOCHS = 100  # ceiling, not a requirement; freeze a common schedule after runtime pilots
MIN_EPOCHS = 10
PATIENCE = 10  # stop after this many validations without improvement
CLEAN_DATA_DIR = None  # optional explicit directory containing metadata.json
RESUME_CHECKPOINT = None  # /kaggle/input/<previous-output>/.../progress.pt
ALLOW_NUMERICAL_UPGRADE = False  # True only for the documented pre-fix AMP checkpoint recovery
FINAL_TEST = False  # enable only after experiment/model choices are frozen
MEASURE_COST = True
SESSION_HOURS = 10.0  # 9h15 training/evaluation + 45 min reserved for safe output
'''
            bootstrap = f'''# Embedded source snapshot; generated by scripts/build_revision_notebooks.py.
# No repository checkout or network installation is required for graph experiments.
import sys
_sources = {sources!r}
_runtime = Path("/kaggle/working/revision_runtime")
_package = _runtime / "spectral_code" / "revision"
_package.mkdir(parents=True, exist_ok=True)
(_package.parent / "__init__.py").write_text("", encoding="utf-8")
for _name, _source in _sources.items():
    (_package / _name).write_text(_source, encoding="utf-8")
sys.path.insert(0, str(_runtime))
from spectral_code.revision.progress import install_progress
install_progress()  # tqdm for data loading, train/evaluation batches and token/embedding caches
'''
            run = '''import json
import torch
from spectral_code.revision.protocol import RunConfig
from spectral_code.revision.model import RevisionModelConfig, RevisionPairModel
from spectral_code.revision.training import (SessionClock, arm_settings, prepare_data,
                                             train_session, evaluate_final)
if not torch.cuda.is_available():
    raise RuntimeError("Enable a Kaggle GPU before Save & Run; CPU runs are for local tests only")
if CLEAN_DATA_DIR is None:
    candidates = []
    for candidate in Path("/kaggle/input").rglob("metadata.json"):
        try:
            if json.loads(candidate.read_text()).get("protocol") == "revision_problem_disjoint_v1":
                candidates.append(candidate.parent)
        except (ValueError, OSError):
            pass
    if len(candidates) != 1:
        raise RuntimeError(f"Attach exactly one audited CodeNet revision bundle or set CLEAN_DATA_DIR. Found: {candidates}")
    CLEAN_DATA_DIR = candidates[0]
CLEAN_DATA_DIR = Path(CLEAN_DATA_DIR)
run_config = RunConfig(seed=SEED, session_hours=SESSION_HOURS, selection_metric="Accuracy",
                       max_epochs=MAX_EPOCHS, min_epochs=MIN_EPOCHS, patience=PATIENCE)
clock = SessionClock(run_config, started=SESSION_STARTED)
frames, graphs, data_hash = prepare_data(CLEAN_DATA_DIR, run_config)
print(json.dumps({"gpu": torch.cuda.get_device_name(0), "torch": torch.__version__,
                  "pair_counts": {split: len(frame) for split, frame in frames.items()},
                  "data_hash": data_hash, "final_test": FINAL_TEST}, indent=2), flush=True)
data_group_hash = data_hash
changes, losses = arm_settings(ARM)
model_config = RevisionModelConfig(max_input_nodes=run_config.max_nodes, **changes)
work_dir = Path("/kaggle/working") / f"revision_{ARM}_seed{SEED}"
summary = train_session(frames, graphs, run_config, model_config, losses, work_dir,
                        data_hash=data_hash,
                        resume=Path(RESUME_CHECKPOINT) if RESUME_CHECKPOINT else None, clock=clock,
                        experiment_label=ARM, data_group_hash=data_group_hash,
                        allow_numerical_upgrade=ALLOW_NUMERICAL_UPGRADE)
print(json.dumps(summary, indent=2))
if MEASURE_COST and summary["complete"]:
    from spectral_code.revision.benchmark import benchmark_checkpoint
    print(json.dumps(benchmark_checkpoint(work_dir / "progress.pt", frames["train"], graphs,
                                         run_config, work_dir / "benchmark.json",
                                         model_factory=RevisionPairModel,
                                         model_config_factory=RevisionModelConfig, clock=clock), indent=2))
if FINAL_TEST:
    if summary["complete"]:
        print(json.dumps(evaluate_final(work_dir / "progress.pt", frames, graphs, run_config,
                                       work_dir, expected_data_hash=data_hash, clock=clock), indent=2))
    else:
        print("No test metrics released: attach progress.pt to a continuation session first.")
'''
            intro = f'''# Reviewer-response CodeNet experiment: {arm}, seed {seed}

This is a new experiment version. It fixes masked slot assignments and uses
angular Chebyshev quadrature, explicit validation accuracy, and audited disjoint
data. Its results must not be mixed with the submitted four-epoch experiment.

One arm/seed runs per Save & Run. The default session is 10 hours with a 45-minute
reserve. Progress is checkpointed every 10 minutes and on a graceful time stop.
Attach that output to the next session and set RESUME_CHECKPOINT. Optimizer,
AMP scaler, random state, validation selection, and optimizer-boundary batch
position resume. A time-limited run remains INCOMPLETE until continued.

The maximum schedule is 100 epochs, with validation patience 10 after at least
10 epochs. Reaching the epoch cap is reported separately from validation stopping.
FINAL_TEST stays False while selecting methods/hyperparameters.
MAX_EPOCHS, MIN_EPOCHS and PATIENCE are editable in the first configuration cell.
Each checkpoint prints a runtime forecast and saves it in status.json. This is
an estimate, not a guarantee or automatic change to the epoch budget. Use pilot
timing and validation curves to freeze a shared schedule before the full study.

Readout controls share input features, latent encoder and symmetric comparison
recipe. Exact parameter counts are reported because readout projections differ.
Mean/max and attention controls retain the shared graph regularizers; their
classification readout does not receive eigenspectrum or filtered-signal features.
'''
            notebook = {"cells": [cell("markdown", intro), cell("code", config), cell("code", bootstrap), cell("code", run)],
                        "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                                     "language_info": {"name": "python", "version": "3.12"},
                                     "kaggle": {"accelerator": "gpu", "isInternetEnabled": False}},
                        "nbformat": 4, "nbformat_minor": 5}
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(json.dumps(notebook, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
            written.append(path)
    # Separate fixed-budget jobs isolate bridge structure from added data.
    # Generate any desired key, or all 166 configurations, via the CLI.
    from spectral_code.revision.transfer import FOCUSED_QUOTAS, write_focused_plan, write_plan
    from spectral_code.revision.transfer_matrix import all_configurations
    write_plan(output / "transfer_plan.csv")
    write_focused_plan(output / "focused_transfer_plan.csv")
    allowed = {c.key for c in all_configurations()} | set(FOCUSED_QUOTAS)
    for key in transfer_keys:
        if key not in allowed:
            raise ValueError(f"Unknown transfer key: {key}")
        for seed in (42, 123, 231):
            notebook = json.loads(written[0].read_text(encoding="utf-8"))
            notebook["cells"][0] = cell("markdown", f'''# Matched-budget transfer: {key}, seed {seed}

Target-language code and labels can appear in training. The held-out object is
the test pair configuration. This control holds training pairs at 6,000 and
optimization at 30 epochs (1,410 optimizer updates), without early stopping.
Validation selects the best checkpoint within that fixed budget. This is a
controlled transfer experiment, not a claim that every model converged.
The same 10-hour session/resume and explicit final-test rules apply.
''')
            config_source = "".join(notebook["cells"][1]["source"])
            config_source = config_source.replace("SEED = 42", f"SEED = {seed}")
            config_source = config_source.replace("MAX_EPOCHS = 100", "MAX_EPOCHS = 30")
            config_source = config_source.replace("MIN_EPOCHS = 10", "MIN_EPOCHS = 30")
            config_source = config_source.replace("PATIENCE = 10", "PATIENCE = 1000")
            config_source += f"\nTRANSFER_KEY = {key!r}\nMATCHED_TRAIN_PAIRS = 6000\n"
            notebook["cells"][1] = cell("code", config_source)
            s = "".join(notebook["cells"][3]["source"])
            needle = "changes, losses = arm_settings(ARM)"
            s = s.replace(needle, '''from spectral_code.revision.transfer import select_transfer_frames
from spectral_code.revision.protocol import fingerprint
frames, transfer_metadata = select_transfer_frames(frames, TRANSFER_KEY, MATCHED_TRAIN_PAIRS, SEED)
data_hash = fingerprint({"bundle": data_hash, "transfer": transfer_metadata})
''' + needle)
            s = s.replace('work_dir = Path("/kaggle/working") / f"revision_{ARM}_seed{SEED}"',
                          'work_dir = Path("/kaggle/working") / ("transfer_" + ARM + "_" + TRANSFER_KEY.replace("|", "_").replace("->", "_") + f"_seed{SEED}")\nwork_dir.mkdir(parents=True, exist_ok=True)\n(work_dir / "transfer_metadata.json").write_text(json.dumps(transfer_metadata, indent=2))')
            s = s.replace("experiment_label=ARM", 'experiment_label=f"transfer/{ARM}/{TRANSFER_KEY}"')
            notebook["cells"][3] = cell("code", s)
            path = output / "03_transfer" / f"{key.replace('|', '_').replace('->', '_')}_seed{seed}.ipynb"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(json.dumps(notebook, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
            written.append(path)
    # Frozen modern encoder and supervised linear probe. Keep extraction and
    # probing in separate sessions, with cached embeddings reused across seeds.
    baseline = json.loads(written[0].read_text(encoding="utf-8"))
    baseline["cells"][0] = cell("markdown", '''# Qwen3-Embedding-0.6B: frozen encoder baseline

Publisher pooling implementation: https://huggingface.co/Qwen/Qwen3-Embedding-0.6B
This is a frozen modern representation with a supervised linear probe; it is
not a fine-tuned code LLM or a reproduction of a specialized CLCD method.
Requires transformers >=4.51, plus Internet for the first model download (or
an already cached model snapshot). Pinning/resuming uses its resolved commit.

Run PHASE="encode" first. Embeddings and row progress survive session limits.
Reattach the output and set RESUME_EMBEDDINGS_DIR to continue extraction.
After extraction is complete, use PHASE="probe" and EMBEDDINGS_DIR pointing to
that attached output. Run seeds 42, 123, 231. FINAL_TEST remains False until
model/protocol decisions are frozen. The same 10-hour/45-minute guard applies.
''')
    baseline["cells"][1] = cell("code", '''from pathlib import Path
import time
SESSION_STARTED = time.monotonic()
SESSION_HOURS = 10.0
SEED = 42
PHASE = "encode"  # encode or probe
CLEAN_DATA_DIR = None
RESUME_EMBEDDINGS_DIR = None
EMBEDDINGS_DIR = None  # completed attached embedding output, for PHASE=probe
RESUME_PROBE_DIR = None
FINAL_TEST = False
''')
    baseline_run = '''import json
from spectral_code.revision.data import CleanDataCorpus, pair_code_ids
from spectral_code.revision.protocol import RunConfig
from spectral_code.revision.training import SessionClock
from spectral_code.revision.embeddings import extract_embeddings, fit_probe
if CLEAN_DATA_DIR is None:
    candidates = [p.parent for p in Path("/kaggle/input").rglob("metadata.json")
                  if json.loads(p.read_text()).get("protocol") == "revision_problem_disjoint_v1"]
    if len(candidates) != 1:
        raise RuntimeError("Attach the audited revision data, or set CLEAN_DATA_DIR explicitly")
    CLEAN_DATA_DIR = candidates[0]
manifest = json.loads((Path(CLEAN_DATA_DIR) / "metadata.json").read_text())
if manifest.get("protocol") != "revision_problem_disjoint_v1" or any(n for v in manifest["overlap"].values() for n in v.values()):
    raise RuntimeError("The baseline requires the same audited disjoint support as the graph experiments")
corpus = CleanDataCorpus(CLEAN_DATA_DIR)
frames = {split: corpus.pairs(split) for split in ("train", "valid", "test")}
clock = SessionClock(RunConfig(seed=SEED, session_hours=SESSION_HOURS), started=SESSION_STARTED)
if PHASE == "encode":
    status = extract_embeddings(corpus.code_texts, sorted(pair_code_ids(*frames.values())),
                                Path("/kaggle/working/qwen3_embeddings"), clock=clock,
                                resume=Path(RESUME_EMBEDDINGS_DIR) if RESUME_EMBEDDINGS_DIR else None)
elif PHASE == "probe":
    if EMBEDDINGS_DIR is None:
        raise ValueError("Set EMBEDDINGS_DIR to the completed extraction output")
    status = fit_probe(frames, Path(EMBEDDINGS_DIR), Path(f"/kaggle/working/qwen3_probe_seed{SEED}"),
                       clock=clock, seed=SEED, final_test=FINAL_TEST,
                       resume=Path(RESUME_PROBE_DIR) if RESUME_PROBE_DIR else None)
else:
    raise ValueError("PHASE must be encode or probe")
print(json.dumps(status, indent=2))
'''
    baseline["cells"][3] = cell("code", baseline_run)
    baseline["metadata"]["kaggle"]["isInternetEnabled"] = True
    path = output / "04_modern_baseline" / "qwen3_frozen_encoder_and_probe.ipynb"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(baseline, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    written.append(path)
    from scripts.revision_notebook_extras import extend
    template = json.loads(written[0].read_text(encoding="utf-8"))
    written.extend(extend(output, template, transfer_keys))
    from scripts.sync_notebook_progress import update_notebook
    for notebook_path in written:
        update_notebook(notebook_path)
    with (output / "notebook_manifest.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=("notebook", "sha256", "group", "seed", "final_test_default"))
        writer.writeheader()
        for notebook_path in written:
            stem = notebook_path.stem
            writer.writerow({"notebook": notebook_path.relative_to(output).as_posix(),
                             "sha256": hashlib.sha256(notebook_path.read_bytes()).hexdigest(),
                             "group": notebook_path.relative_to(output).parts[0],
                             "seed": stem.rsplit("seed", 1)[1] if "seed" in stem else "configured in notebook",
                             "final_test_default": "False" if "08_analysis" not in notebook_path.parts else "analysis only"})
    return written


if __name__ == "__main__":
    import sys
    sys.path.insert(0, str(ROOT))
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--transfer-key", action="append", help="Repeat for selected keys from transfer_plan.csv; defaults to table8|J->P")
    parser.add_argument("--all-transfer", action="store_true", help="Generate all 166 configurations, three seeds each")
    args = parser.parse_args()
    from spectral_code.revision.transfer_matrix import all_configurations
    keys = tuple(c.key for c in all_configurations()) if args.all_transfer else tuple(args.transfer_key or ("table8|J->P",))
    print(f"Generated {len(build(args.output, keys))} standalone arm/seed notebooks")
